#!/usr/bin/env python3
"""Gate of the book's information architecture (rule project.information-architecture).

Every page is judged against the same requirements. Pages that did not meet them when the
gate was introduced are listed in scripts/ia-baseline.json; the gate fails on any violation
that is not in the baseline, so the architecture can only get better. `--update-baseline`
removes what has been fixed and refuses to add anything.

Requirements (id: what is checked):
  front-matter     the page has parseable front matter with a title
  toml             the front matter is TOML (+++), as on every other page
  description      a top-level description of 50-200 characters (not under [extra])
  tags             at least one tag under [taxonomies] (not under [extra])
  czech            the prose is Czech (more Czech than English function words)
  diacritics       Czech prose carries diacritics (at least 3 % of words)
  related          a `## Související` section (index pages exempt)
  links-out        at least 3 internal @/ links to existing pages (index pages exempt)
  not-orphan       at least one other page links here (index pages exempt)
  broken-link      no @/ link points at a page that does not exist
  placeholder      no placeholder, stub or generated filler (rule content-no-placeholders);
                   never accepted into the baseline: it fails on every page, always
  thin             at least 600 words of prose: a page is written out, not sketched
  bullets          no list items outside the Související and Literatura sections: every
                   point is a paragraph (rule content-academic-style)
  citations        every paragraph of 20+ words carries a citation (Autor, rok) or a law
  bibliography     a `## Literatura` section with full entries "Příjmení, I. (rok). …"
  citation-unresolved  every cited author appears in the page's Literatura section
  category         a glossary entry's extra.category is one of GLOSSARY_CATEGORIES
  term-links       the first mention of every glossary term in the prose is a link to its
                   entry (scripts/link-terms.py inserts them)
  technique-page   every technique code EA-X.Y.Z the page names has its own page (by file
                   name or ea_code); never accepted into the baseline, like a broken link

Usage:
  scripts/check-ia.py                    fail on new violations; print the summary
  scripts/check-ia.py --update-baseline  shrink the baseline to what still fails
  scripts/check-ia.py --list <rule>      list the pages that violate one requirement
  scripts/check-ia.py --page <path>...   every violation of the named pages, baseline or not
  scripts/check-ia.py --adopt <rule>     admit a newly introduced requirement: record its
                                         current violations once; refused when the baseline
                                         already carries the rule or the rule is placeholder
"""
import collections
import json
import pathlib
import sys

sys.dont_write_bytecode = True  # no __pycache__ in the checkout
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from ia_model import GLOSSARY_CATEGORIES, MIN_PAGE_WORDS, ROOT, load_pages  # noqa: E402

BASELINE = ROOT / "scripts" / "ia-baseline.json"
EXEMPT = {"content/references.md"}  # generated by scripts/build-references.py
NEVER_BASELINED = {"placeholder", "technique-page"}  # an unfinished page is never an accepted state


def violations(page: dict) -> list:
    found = []
    if not page["front_matter"] or page["front_matter_error"] or not page["title"]:
        found.append("front-matter")
    if page["front_matter"] != "toml":
        found.append("toml")
    if not 50 <= len(page["description"]) <= 200:
        found.append("description")
    if not page["tags"] and not page["is_index"]:  # Zola sections take no taxonomies
        found.append("tags")
    if page["words"] >= 50:
        if page["language"] == "en":
            found.append("czech")
        elif page["diacritics"] < 0.03:
            found.append("diacritics")
    if not page["is_index"]:
        if not page["has_related"]:
            found.append("related")
        if len(page["links"]) < 3:
            found.append("links-out")
        if page["links_in"] == 0:
            found.append("not-orphan")
    if page["broken_links"]:
        found.append("broken-link")
    if page["placeholders"]:
        found.append("placeholder")
    if page["words"] < MIN_PAGE_WORDS:
        found.append("thin")
    if page["loose_bullets"]:
        found.append("bullets")
    if page["uncited_paragraphs"]:
        found.append("citations")
    if not page["bibliography_entries"]:
        found.append("bibliography")
    if page["unresolved_citations"]:
        found.append("citation-unresolved")
    if page["unlinked_terms"]:
        found.append("term-links")
    if page["missing_techniques"]:
        found.append("technique-page")
    if page["path"].startswith("glossary/") and not page["is_index"] \
            and page["category"] not in GLOSSARY_CATEGORIES:
        found.append("category")
    return found


def explain(page: dict, rules: list) -> str:
    detail = {
        "placeholder": ", ".join(page["placeholders"]),
        "thin": f"{page['words']} words",
        "bullets": f"{page['loose_bullets']} list item(s)",
        "citations": f"{page['uncited_paragraphs']} paragraph(s) without a citation",
        "citation-unresolved": ", ".join(page["unresolved_citations"]),
        "links-out": f"{len(page['links'])} link(s)",
        "broken-link": ", ".join(page["broken_links"]),
        "term-links": ", ".join(f"„{t[0]}“" for t in page["unlinked_terms"][:8])
        + (" …" if len(page["unlinked_terms"]) > 8 else ""),
        "technique-page": ", ".join("EA-" + c for c in page["missing_techniques"]),
        "category": f"'{page['category']}' is not in GLOSSARY_CATEGORIES",
    }
    return ", ".join(f"{r} ({detail[r]})" if detail.get(r) else r for r in rules)


def current(pages=None) -> dict:
    result = {}
    for page in pages if pages is not None else load_pages():
        key = f"content/{page['path']}"
        if key in EXEMPT:
            continue
        found = violations(page)
        if found:
            result[key] = found
    return result


def main() -> int:
    args = sys.argv[1:]
    pages = load_pages()
    now = current(pages)
    if "--page" in args:
        wanted = {a if a.startswith("content/") else f"content/{a}"
                  for a in args[args.index("--page") + 1:]}
        by_path = {f"content/{p['path']}": p for p in pages}
        bad = 0
        for path in sorted(wanted):
            if path not in by_path:
                print(f"{path}: no such page"); bad += 1; continue
            rules = now.get(path, [])
            print(f"{path}: {'ok' if not rules else explain(by_path[path], rules)}")
            bad += bool(rules)
        return 1 if bad else 0
    if "--list" in args:
        rule = args[args.index("--list") + 1]
        for path, rules in sorted(now.items()):
            if rule in rules:
                print(path)
        return 0
    baseline = json.loads(BASELINE.read_text(encoding="utf-8")) if BASELINE.exists() else {}
    for rules in baseline.values():  # a hand-edited baseline cannot excuse a placeholder
        rules[:] = [r for r in rules if r not in NEVER_BASELINED]
    if "--adopt" in args:
        rule = args[args.index("--adopt") + 1]
        if rule in NEVER_BASELINED:
            print(f"check-ia: {rule} is never accepted into the baseline"); return 1
        if any(rule in rules for rules in baseline.values()):
            print(f"check-ia: {rule} is already in the baseline; it can only shrink"); return 1
        added = 0
        for path, rules in now.items():
            if rule in rules:
                baseline.setdefault(path, []).append(rule); added += 1
        BASELINE.write_text(json.dumps({p: sorted(r) for p, r in baseline.items() if r},
                                       ensure_ascii=False, indent=1, sort_keys=True)
                            + "\n", encoding="utf-8")
        print(f"check-ia: adopted {rule} with {added} existing violation(s)")
        return 0
    counts = collections.Counter(r for rules in now.values() for r in rules)
    fresh = {p: [r for r in rules if r not in baseline.get(p, [])] for p, rules in now.items()}
    fresh = {p: r for p, r in fresh.items() if r}

    if "--update-baseline" in args:
        if fresh and BASELINE.exists():
            print(f"check-ia: refusing to grow the baseline: {len(fresh)} page(s) have new "
                  "violations; fix them first")
            return 1
        shrunk = {p: [r for r in rules if r in now.get(p, [])] for p, rules in baseline.items()}
        shrunk = {p: r for p, r in shrunk.items() if r} if BASELINE.exists() else now
        BASELINE.write_text(json.dumps(shrunk, ensure_ascii=False, indent=1, sort_keys=True)
                            + "\n", encoding="utf-8")
        before = sum(len(r) for r in baseline.values())
        after = sum(len(r) for r in shrunk.values())
        print(f"check-ia: baseline {before} -> {after} violation(s)")
        return 0

    total = sum(counts.values())
    print(f"check-ia: {total} violation(s) on {len(now)} page(s); "
          + ", ".join(f"{r} {n}" for r, n in counts.most_common()))
    fixed = sum(len(r) for r in baseline.values()) - sum(
        len([x for x in rules if x in now.get(p, [])]) for p, rules in baseline.items())
    if fixed:
        print(f"check-ia: {fixed} baseline violation(s) fixed; run --update-baseline to lock them in")
    if fresh:
        print(f"check-ia: FAIL — {sum(len(r) for r in fresh.values())} new violation(s):")
        by_path = {f"content/{p['path']}": p for p in pages}
        # Violations the baseline can never excuse come first, so the cap never hides them.
        ordered = sorted(fresh.items(), key=lambda kv: (not set(kv[1]) & NEVER_BASELINED, kv[0]))
        for path, rules in ordered[:60]:
            print(f"  {path}: {explain(by_path[path], rules)}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
